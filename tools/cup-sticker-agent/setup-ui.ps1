#Requires -Version 5.1
<#
.SYNOPSIS
  GUI setup for Bing Chun cup sticker agent:
  - auto-detect printers (name, USB/COM/TCP port, IP)
  - change printer port or network IP
  - write local.env
  - install Windows Service (boot start) or Startup fallback
  - start agent / restart after reinstall
#>
param(
  [string]$ApiUrl = 'https://admin.bingchunsrilanka.com/api',
  [string]$Secret = 'bingchun-cup-sticker-local'
)

Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'

$AgentDir = Split-Path -Parent $MyInvocation.MyCommand.Path
$LocalEnv = Join-Path $AgentDir 'local.env'
$ListPs1 = Join-Path $AgentDir 'list-printers.ps1'
$SetPortPs1 = Join-Path $AgentDir 'set-printer-port.ps1'
$InstallPs1 = Join-Path $AgentDir 'install.ps1'
$ServiceName = 'BingChunCupStickerAgent'

Add-Type -AssemblyName System.Windows.Forms
