$btnInstall.Add_Click({
  try {
    $name = $txtPrinter.Text.Trim()
    if (-not $name) { throw 'Select or type the printer name.' }
    $port = $cmbPort.Text.Trim()
    $ip = $txtIp.Text.Trim()
    $tcp = $txtTcp.Text.Trim()
    Save-LocalEnv -printer $name -portName $port -hostAddress $ip -tcpPort $tcp
    Set-Status "Saved local.env. Running install (Node deps + Windows Service / Startup)..."
    $form.Refresh()
    & powershell.exe -NoProfile -ExecutionPolicy Bypass -File $InstallPs1 -PrinterName $name
    if ($LASTEXITCODE -ne 0) { throw "install.ps1 exited $LASTEXITCODE" }
    Set-Status "Installed. Printer=$name Port=$port IP=$ip  Health: http://127.0.0.1:9177/health  Re-run this setup anytime if the port/IP changes."
  } catch {
    Set-Status $_.Exception.Message $false
  }
})
