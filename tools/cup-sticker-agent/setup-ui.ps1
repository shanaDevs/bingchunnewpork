$btnApplyPort = New-Object System.Windows.Forms.Button
$btnApplyPort.Text = 'Apply port / IP'
$btnApplyPort.Location = New-Object System.Drawing.Point(145, 375)
$btnApplyPort.Size = New-Object System.Drawing.Size(130, 30)
$btnApplyPort.Add_Click({
  try {
    $name = $txtPrinter.Text.Trim()
    if (-not $name) { throw 'Enter a printer name.' }
    $ip = $txtIp.Text.Trim()
    if ($ip) {
      $tcp = 9100
      [void][int]::TryParse($txtTcp.Text.Trim(), [ref]$tcp)
      & powershell.exe -NoProfile -ExecutionPolicy Bypass -File $SetPortPs1 -PrinterName $name -HostAddress $ip -TcpPort $tcp
    } else {
      $port = $cmbPort.Text.Trim()
      if (-not $port) { throw 'Pick a Windows port or enter a network IP.' }
      & powershell.exe -NoProfile -ExecutionPolicy Bypass -File $SetPortPs1 -PrinterName $name -PortName $port
    }
    Set-Status "Port updated for '$name'. Refreshing..."
    Refresh-List
  } catch {
    Set-Status $_.Exception.Message $false
  }
})
$form.Controls.Add($btnApplyPort)

