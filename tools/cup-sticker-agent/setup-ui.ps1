function Set-Status([string]$msg, [bool]$ok = $true) {
  $status.ForeColor = if ($ok) { [System.Drawing.Color]::DarkGreen } else { [System.Drawing.Color]::Firebrick }
  $status.Text = $msg
}

function Refresh-List {
  Set-Status 'Scanning printers...'
  $snap = Get-PrinterSnapshot
  $grid.DataSource = $null
  $cmbPort.Items.Clear()

  if (-not $snap) {
    Set-Status 'No printer data returned.' $false
    return
  }

  $table = New-Object System.Data.DataTable
  [void]$table.Columns.Add('Name')
  [void]$table.Columns.Add('Driver')
  [void]$table.Columns.Add('Port')
  [void]$table.Columns.Add('IP')
  [void]$table.Columns.Add('TCP')
  [void]$table.Columns.Add('Kind')
  [void]$table.Columns.Add('Ready')
  [void]$table.Columns.Add('Sticker?')

  foreach ($p in @($snap.printers)) {
    $row = $table.NewRow()
    $row['Name'] = $p.name
    $row['Driver'] = $p.driverName
    $row['Port'] = $p.portName
    $row['IP'] = $p.hostAddress
    $row['TCP'] = if ($null -ne $p.tcpPort) { [string]$p.tcpPort } else { '' }
    $row['Kind'] = $p.portKind
    $row['Ready'] = if ($p.ready) { 'Yes' } else { 'No' }
    $row['Sticker?'] = if ($p.stickerLikely) { 'Yes' } else { '' }
    [void]$table.Rows.Add($row)
  }
  $grid.DataSource = $table

  foreach ($port in @($snap.ports)) {
    if ($port.portName) { [void]$cmbPort.Items.Add($port.portName) }
  }

  $pick = [string]$snap.suggested
  if (-not $pick -and $snap.printers.Count -gt 0) {
    $pick = [string]$snap.printers[0].name
  }
  if ($pick) {
    $txtPrinter.Text = $pick
    $match = @($snap.printers | Where-Object { $_.name -eq $pick } | Select-Object -First 1)
    if ($match) {
      $cmbPort.Text = [string]$match.portName
      $txtIp.Text = [string]$match.hostAddress
      if ($null -ne $match.tcpPort -and [string]$match.tcpPort -ne '') {
        $txtTcp.Text = [string]$match.tcpPort
      }
    }
  }

  $hint = if ($snap.suggested) { "Suggested: $($snap.suggested)" } else { 'No Xprinter/bingchun queue auto-detected.' }
  Set-Status "$hint  — select a row or edit fields, then Save && Install."
}

$grid.add_SelectionChanged({
  if ($grid.CurrentRow -and -not $grid.CurrentRow.IsNewRow) {
    $txtPrinter.Text = [string]$grid.CurrentRow.Cells['Name'].Value
    $cmbPort.Text = [string]$grid.CurrentRow.Cells['Port'].Value
    $txtIp.Text = [string]$grid.CurrentRow.Cells['IP'].Value
    $tcpVal = [string]$grid.CurrentRow.Cells['TCP'].Value
    if ($tcpVal) { $txtTcp.Text = $tcpVal }
  }
})

