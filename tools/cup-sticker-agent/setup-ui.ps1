function Get-PrinterSnapshot {
  $raw = & powershell.exe -NoProfile -ExecutionPolicy Bypass -File $ListPs1
  if (-not $raw) { return $null }
  return ($raw | Out-String) | ConvertFrom-Json
}

function Save-LocalEnv([string]$printer, [string]$portName, [string]$hostAddress, [string]$tcpPort) {
  $lines = @(
    '# Auto-generated by setup-ui.ps1 - re-run setup / install.bat to refresh',
    "BC_STICKER_API_URL=$ApiUrl",
    "BC_STICKER_SECRET=$Secret",
    "BC_STICKER_PRINTER=$printer",
    "BC_STICKER_PRINTER_PORT=$portName",
    "BC_STICKER_PRINTER_HOST=$hostAddress",
    "BC_STICKER_PRINTER_TCP_PORT=$tcpPort",
    'BC_STICKER_WIDTH_MM=40',
    'BC_STICKER_HEIGHT_MM=30',
    'BC_STICKER_STORE_ID=',
    'BC_STICKER_SILENT=1'
  )
  [System.IO.File]::WriteAllLines($LocalEnv, $lines)
}

