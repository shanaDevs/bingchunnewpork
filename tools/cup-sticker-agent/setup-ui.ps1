$btnReinstall.Add_Click({
  try {
    $name = $txtPrinter.Text.Trim()
    if (-not $name) { throw 'Select printer first.' }
    $ip = $txtIp.Text.Trim()
    if ($ip) {
      $tcp = 9100
      [void][int]::TryParse($txtTcp.Text.Trim(), [ref]$tcp)
      & powershell.exe -NoProfile -ExecutionPolicy Bypass -File $SetPortPs1 -PrinterName $name -HostAddress $ip -TcpPort $tcp
    } elseif ($cmbPort.Text.Trim()) {
      & powershell.exe -NoProfile -ExecutionPolicy Bypass -File $SetPortPs1 -PrinterName $name -PortName $cmbPort.Text.Trim()
    }
    Save-LocalEnv -printer $name -portName $cmbPort.Text.Trim() -hostAddress $ip -tcpPort $txtTcp.Text.Trim()
    & powershell.exe -NoProfile -ExecutionPolicy Bypass -File $InstallPs1 -PrinterName $name
