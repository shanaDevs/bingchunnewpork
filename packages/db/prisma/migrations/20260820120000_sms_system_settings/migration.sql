-- SMSlenz gateway credentials on system_settings (admin Settings UI)

ALTER TABLE "system_settings"
  ADD COLUMN IF NOT EXISTS "smsEnabled" BOOLEAN NOT NULL DEFAULT false,
  ADD COLUMN IF NOT EXISTS "smsProvider" VARCHAR(32) NOT NULL DEFAULT 'smslenz',
  ADD COLUMN IF NOT EXISTS "smsUserId" VARCHAR(191) NULL,
  ADD COLUMN IF NOT EXISTS "smsApiKey" TEXT NULL,
  ADD COLUMN IF NOT EXISTS "smsSenderId" VARCHAR(64) NULL,
  ADD COLUMN IF NOT EXISTS "smsBaseUrl" VARCHAR(512) NULL,
  ADD COLUMN IF NOT EXISTS "smsConnectionTimeoutMs" INTEGER NOT NULL DEFAULT 30000,
  ADD COLUMN IF NOT EXISTS "smsReadTimeoutMs" INTEGER NOT NULL DEFAULT 30000;
